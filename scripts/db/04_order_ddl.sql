USE `ticket_booking`;

-- 订单表
CREATE TABLE IF NOT EXISTS `order` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '订单ID',
    `order_no` VARCHAR(32) NOT NULL COMMENT '订单号',
    `user_id` BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
    `ticket_id` BIGINT UNSIGNED NOT NULL COMMENT '票务ID',
    `session_id` BIGINT UNSIGNED NOT NULL COMMENT '场次ID',
    `venue_id` BIGINT UNSIGNED NOT NULL COMMENT '场馆ID',
    `venue_name` VARCHAR(100) NOT NULL COMMENT '场馆名称',
    `ticket_name` VARCHAR(200) NOT NULL COMMENT '票务名称',
    `show_date` DATE NOT NULL COMMENT '演出日期',
    `show_time` TIME NOT NULL COMMENT '演出时间',
    `total_quantity` INT NOT NULL COMMENT '总数量',
    `total_amount` DECIMAL(15,2) NOT NULL COMMENT '订单总金额',
    `discount_amount` DECIMAL(15,2) DEFAULT 0.00 COMMENT '优惠金额',
    `pay_amount` DECIMAL(15,2) NOT NULL COMMENT '实付金额',
    `coupon_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '优惠券ID',
    `coupon_amount` DECIMAL(10,2) DEFAULT 0.00 COMMENT '优惠券优惠金额',
    `point_discount` DECIMAL(10,2) DEFAULT 0.00 COMMENT '积分抵扣金额',
    `order_status` TINYINT NOT NULL DEFAULT 1 COMMENT '订单状态: 1-待支付, 2-已支付, 3-已完成, 4-已取消, 5-已退款, 6-退款中',
    `pay_status` TINYINT NOT NULL DEFAULT 0 COMMENT '支付状态: 0-未支付, 1-已支付, 2-已退款',
    `pay_time` DATETIME DEFAULT NULL COMMENT '支付时间',
    `pay_channel` VARCHAR(20) DEFAULT NULL COMMENT '支付渠道: alipay, wechat, bank',
    `trade_no` VARCHAR(64) DEFAULT NULL COMMENT '第三方交易号',
    `remark` VARCHAR(500) DEFAULT NULL COMMENT '订单备注',
    `contact_name` VARCHAR(50) NOT NULL COMMENT '联系人姓名',
    `contact_phone` VARCHAR(20) NOT NULL COMMENT '联系人手机',
    `contact_id_card` VARCHAR(50) DEFAULT NULL COMMENT '联系人身份证',
    `user_remark` VARCHAR(255) DEFAULT NULL COMMENT '用户备注',
    `cancel_time` DATETIME DEFAULT NULL COMMENT '取消时间',
    `cancel_reason` VARCHAR(255) DEFAULT NULL COMMENT '取消原因',
    `complete_time` DATETIME DEFAULT NULL COMMENT '完成时间',
    `expire_time` DATETIME NOT NULL COMMENT '订单过期时间',
    `ip_address` VARCHAR(50) DEFAULT NULL COMMENT '下单IP',
    `source` VARCHAR(20) DEFAULT NULL COMMENT '订单来源',
    `inventory_restored` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '库存是否已回补',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted_at` DATETIME DEFAULT NULL COMMENT '删除时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_order_no` (`order_no`),
    KEY `idx_user_id` (`user_id`),
    KEY `idx_ticket_id` (`ticket_id`),
    KEY `idx_session_id` (`session_id`),
    KEY `idx_order_status` (`order_status`),
    KEY `idx_pay_status` (`pay_status`),
    KEY `idx_expire_time` (`expire_time`),
    KEY `idx_created_at` (`created_at`),
    KEY `idx_show_date` (`show_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='订单表';

-- 订单明细表
CREATE TABLE IF NOT EXISTS `order_item` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '明细ID',
    `order_id` BIGINT UNSIGNED NOT NULL COMMENT '订单ID',
    `order_no` VARCHAR(32) NOT NULL COMMENT '订单号',
    `ticket_id` BIGINT UNSIGNED NOT NULL COMMENT '票务ID',
    `session_id` BIGINT UNSIGNED NOT NULL COMMENT '场次ID',
    `price_level_id` BIGINT UNSIGNED NOT NULL COMMENT '票档ID',
    `price_level_name` VARCHAR(100) NOT NULL COMMENT '票档名称',
    `seat_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '座位ID',
    `seat_no` VARCHAR(50) DEFAULT NULL COMMENT '座位号',
    `quantity` INT NOT NULL DEFAULT 1 COMMENT '数量',
    `unit_price` DECIMAL(10,2) NOT NULL COMMENT '单价',
    `subtotal` DECIMAL(15,2) NOT NULL COMMENT '小计金额',
    `status` TINYINT NOT NULL DEFAULT 1 COMMENT '状态: 1-正常, 0-已退款',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_order_id` (`order_id`),
    KEY `idx_session_id` (`session_id`),
    KEY `idx_seat_id` (`seat_id`),
    KEY `idx_price_level_id` (`price_level_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='订单明细表';

-- 支付记录表
CREATE TABLE IF NOT EXISTS `payment` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '支付记录ID',
    `payment_id` VARCHAR(64) NOT NULL COMMENT '支付流水号',
    `order_id` BIGINT UNSIGNED NOT NULL COMMENT '订单ID',
    `order_no` VARCHAR(32) NOT NULL COMMENT '订单号',
    `user_id` BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
    `amount` DECIMAL(15,2) NOT NULL COMMENT '支付金额',
    `actual_amount` DECIMAL(15,2) DEFAULT NULL COMMENT '实际支付金额',
    `pay_channel` VARCHAR(20) NOT NULL COMMENT '支付渠道: alipay, wechat, bank, balance',
    `pay_method` VARCHAR(20) DEFAULT NULL COMMENT '支付方式: app, web, h5, qrcode',
    `trade_type` VARCHAR(20) DEFAULT NULL COMMENT '交易类型',
    `trade_no` VARCHAR(64) DEFAULT NULL COMMENT '第三方交易号',
    `trade_status` VARCHAR(20) DEFAULT NULL COMMENT '第三方交易状态',
    `pay_status` TINYINT NOT NULL DEFAULT 0 COMMENT '支付状态: 0-待支付, 1-支付中, 2-已支付, 3-支付失败, 4-已退款',
    `pay_time` DATETIME DEFAULT NULL COMMENT '支付成功时间',
    `expire_time` DATETIME NOT NULL COMMENT '支付过期时间',
    `notify_time` DATETIME DEFAULT NULL COMMENT '异步通知时间',
    `notify_data` JSON DEFAULT NULL COMMENT '异步通知原始数据',
    `client_ip` VARCHAR(50) DEFAULT NULL COMMENT '客户端IP',
    `device_info` VARCHAR(255) DEFAULT NULL COMMENT '设备信息',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_payment_id` (`payment_id`),
    KEY `idx_order_id` (`order_id`),
    KEY `idx_user_id` (`user_id`),
    KEY `idx_pay_status` (`pay_status`),
    KEY `idx_trade_no` (`trade_no`),
    KEY `idx_expire_time` (`expire_time`),
    KEY `idx_pay_time` (`pay_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='支付记录表';

-- 退款表
CREATE TABLE IF NOT EXISTS `refund` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '退款ID',
    `refund_no` VARCHAR(32) NOT NULL COMMENT '退款单号',
    `order_id` BIGINT UNSIGNED NOT NULL COMMENT '订单ID',
    `order_no` VARCHAR(32) NOT NULL COMMENT '订单号',
    `payment_id` BIGINT UNSIGNED NOT NULL COMMENT '支付记录ID',
    `user_id` BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
    `refund_amount` DECIMAL(15,2) NOT NULL COMMENT '退款金额',
    `refund_type` TINYINT NOT NULL DEFAULT 1 COMMENT '退款类型: 1-用户申请, 2-系统退款, 3-风控退款',
    `refund_reason_type` TINYINT NOT NULL COMMENT '退款原因类型: 1-用户取消, 2-重复支付, 3-支付超时, 4-商家取消, 5-演出取消, 6-其他',
    `refund_reason` VARCHAR(500) NOT NULL COMMENT '退款原因',
    `refund_status` TINYINT NOT NULL DEFAULT 0 COMMENT '退款状态: 0-待处理, 1-处理中, 2-已完成, 3-已拒绝',
    `refund_channel` VARCHAR(20) DEFAULT NULL COMMENT '退款渠道',
    `refund_trade_no` VARCHAR(64) DEFAULT NULL COMMENT '退款交易号',
    `refund_time` DATETIME DEFAULT NULL COMMENT '退款完成时间',
    `audit_user_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '审核人ID',
    `audit_time` DATETIME DEFAULT NULL COMMENT '审核时间',
    `audit_remark` VARCHAR(255) DEFAULT NULL COMMENT '审核备注',
    `reject_reason` VARCHAR(255) DEFAULT NULL COMMENT '拒绝原因',
    `operator_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '操作员ID',
    `process_data` JSON DEFAULT NULL COMMENT '处理数据',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_refund_no` (`refund_no`),
    KEY `idx_order_id` (`order_id`),
    KEY `idx_user_id` (`user_id`),
    KEY `idx_refund_status` (`refund_status`),
    KEY `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='退款表';

-- 库存流水表
CREATE TABLE IF NOT EXISTS `inventory_log` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '日志ID',
    `ticket_id` BIGINT UNSIGNED NOT NULL COMMENT '票务ID',
    `session_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '场次ID',
    `price_level_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '票档ID',
    `seat_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '座位ID',
    `change_type` TINYINT NOT NULL COMMENT '变动类型: 1-创建, 2-锁定, 3-释放, 4-售出, 5-退款返还, 6-人工调整',
    `before_stock` INT NOT NULL COMMENT '变动前库存',
    `change_num` INT NOT NULL COMMENT '变动数量',
    `after_stock` INT NOT NULL COMMENT '变动后库存',
    `order_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '关联订单ID',
    `operator_id` BIGINT UNSIGNED DEFAULT NULL COMMENT '操作人ID',
    `operator_type` TINYINT DEFAULT 1 COMMENT '操作类型: 1-系统, 2-用户, 3-管理员',
    `remark` VARCHAR(255) DEFAULT NULL COMMENT '备注',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    KEY `idx_ticket_id` (`ticket_id`),
    KEY `idx_session_id` (`session_id`),
    KEY `idx_order_id` (`order_id`),
    KEY `idx_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='库存流水表';
